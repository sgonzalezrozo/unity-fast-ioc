#if UNITY_EDITOR
using System.Text;

namespace FastIoC.Editor.Generation
{
    /// <summary>
    /// Emits GeneratedModule: the IGeneratedModule implementation that registers the generated code with
    /// the runtime through [RuntimeInitializeOnLoadMethod], so the runtime never searches for generated types.
    /// It also registers in the editor ([InitializeOnLoadMethod]) so the scene baker can use it.
    /// </summary>
    public static class GeneratedModuleEmitter
    {
        public static string GenerateModule()
        {
            StringBuilder sb = new();

            sb.AppendLine("// <auto-generated> FastIoC. Do not edit: regenerate with Tools > FastIoC > Regenerate Code. </auto-generated>");
            sb.AppendLine("namespace FastIoCGenerated");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Connects the generated code to the FastIoC runtime with direct calls (no reflection).");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    [global::UnityEngine.Scripting.Preserve]");
            sb.AppendLine("    internal sealed class GeneratedModule : global::FastIoC.Core.IGeneratedModule");
            sb.AppendLine("    {");
            sb.AppendLine("        [global::UnityEngine.Scripting.Preserve]");
            sb.AppendLine("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
            sb.AppendLine("        private static void RegisterAtStartup()");
            sb.AppendLine("        {");
            sb.AppendLine("            // Runs on every Play Mode start, also with Domain Reload disabled, so static state is reset here.");
            sb.AppendLine("            GeneratedInstanceRegistry.Clear();");
            sb.AppendLine("            global::FastIoC.Core.GeneratedModuleRegistry.Register(new GeneratedModule());");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("#if UNITY_EDITOR");
            sb.AppendLine("        [global::UnityEditor.InitializeOnLoadMethod]");
            sb.AppendLine("        private static void RegisterInEditor()");
            sb.AppendLine("        {");
            sb.AppendLine("            global::FastIoC.Core.GeneratedModuleRegistry.Register(new GeneratedModule());");
            sb.AppendLine("        }");
            sb.AppendLine("#endif");
            sb.AppendLine();
            sb.AppendLine("        public void EnsureInitialized() => GeneratedRegistry.EnsureInitialized();");
            sb.AppendLine();
            sb.AppendLine("        public global::FastIoC.Core.ContextRuntime CreateSceneContextRuntime(string sceneName) => GeneratedRegistry.CreateSceneContextRuntime(sceneName);");
            sb.AppendLine();
            sb.AppendLine("        public global::FastIoC.Core.ContextRuntime CreateProjectContextRuntime() => GeneratedRegistry.CreateProjectContextRuntime();");
            sb.AppendLine();
            sb.AppendLine("        public void InitializeInstances() => InstanceRegistryInitializer.InitializeInstances();");
            sb.AppendLine();
            sb.AppendLine("        public object GetInstance(int typeId) => GeneratedInstanceRegistry.GetInstance(typeId);");
            sb.AppendLine();
            sb.AppendLine("        public int GetInjectorId(global::System.Type monoBehaviourType) => GeneratedMonoInjectors.GetInjectorId(monoBehaviourType);");
            sb.AppendLine();
            sb.AppendLine("        public void InjectAt(int injectorId, global::UnityEngine.MonoBehaviour target, global::FastIoC.Core.ContextRuntime context)");
            sb.AppendLine("            => GeneratedMonoInjectors.InjectAt(injectorId, target, context);");
            sb.AppendLine();
            sb.AppendLine("        public bool InjectChildrenData(global::UnityEngine.MonoBehaviour target, object data)");
            sb.AppendLine("            => GeneratedMonoInjectors.InjectChildrenData(target, data);");
            sb.AppendLine();
            sb.AppendLine("        public void InjectLocal(global::UnityEngine.MonoBehaviour target, global::FastIoC.Core.ILocalComponentSource source)");
            sb.AppendLine("            => GeneratedMonoInjectors.InjectLocal(target, source);");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }
    }
}
#endif
