#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor.Compilation;
using Assembly = System.Reflection.Assembly;
using UnityEngine;

namespace FastIoC.Editor.Generation
{
    /// <summary>
    /// Decides which assemblies must expose their internals to Assembly-CSharp so the generated
    /// injectors can assign `internal` fields directly, and writes the InternalsVisibleTo files.
    ///
    /// An assembly whose .asmdef lives under Assets/ gets a generated
    /// FastIoC.InternalsVisibleTo.g.cs next to its .asmdef. Assemblies in packages are never modified:
    /// they need [assembly: InternalsVisibleTo("Assembly-CSharp")] added by hand, otherwise their
    /// internal fields fall back to reflection (and generation logs which ones).
    /// </summary>
    internal sealed class InternalsAccessPlan
    {
        public const string IVT_FILE_NAME = "FastIoC.InternalsVisibleTo.g.cs";

        private const string IVT_FILE_CONTENT =
            "// <auto-generated>\n" +
            "// Written by FastIoC code generation. Lets the generated injectors in Assembly-CSharp\n" +
            "// assign `internal` fields of this assembly directly, without reflection.\n" +
            "// </auto-generated>\n" +
            "[assembly: System.Runtime.CompilerServices.InternalsVisibleTo(\"Assembly-CSharp\")]\n";

        private readonly Dictionary<string, string> writableFolders = new();
        private readonly HashSet<string> playerAssemblyNames = new();
        private readonly HashSet<Assembly> required = new();

        public IReadOnlyCollection<string> PlayerAssemblyNames => playerAssemblyNames;

        public static InternalsAccessPlan Create()
        {
            CodeGenTypeUtility.ClearCache();
            InternalsAccessPlan plan = new();
            plan.playerAssemblyNames.Add(CodeGenTypeUtility.GENERATED_ASSEMBLY_NAME);

            try
            {
                foreach (UnityEditor.Compilation.Assembly compiledAssembly in CompilationPipeline.GetAssemblies(AssembliesType.PlayerWithoutTestAssemblies))
                {
                    plan.playerAssemblyNames.Add(compiledAssembly.name);

                    string asmdefPath = CompilationPipeline.GetAssemblyDefinitionFilePathFromAssemblyName(compiledAssembly.name);
                    if (string.IsNullOrEmpty(asmdefPath))
                        continue;

                    asmdefPath = asmdefPath.Replace('\\', '/');
                    if (!asmdefPath.StartsWith("Assets/", StringComparison.Ordinal))
                        continue;

                    plan.writableFolders[compiledAssembly.name] = Path.GetDirectoryName(asmdefPath)?.Replace('\\', '/');
                }
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[FastIoC] Could not read the compilation pipeline assemblies: {ex.Message}");
            }

            return plan;
        }

        /// <summary>True if Assembly-CSharp can (or will, after this generation) see the internals of <paramref name="assembly"/>.</summary>
        public bool Grants(Assembly assembly)
        {
            if (assembly == null)
                return false;

            return CodeGenTypeUtility.AlreadyGrantsInternals(assembly) || writableFolders.ContainsKey(assembly.GetName().Name);
        }

        /// <summary>Records that generated code uses internals of <paramref name="assembly"/>.</summary>
        public void Require(Assembly assembly)
        {
            if (assembly != null && !CodeGenTypeUtility.AlreadyGrantsInternals(assembly))
                required.Add(assembly);
        }

        /// <summary>Records the assemblies needed to name <paramref name="type"/>.</summary>
        public void RequireForType(Type type)
        {
            HashSet<Assembly> assemblies = new();
            CodeGenTypeUtility.CollectInternalAssemblies(type, assemblies);
            foreach (Assembly assembly in assemblies)
                Require(assembly);
        }

        /// <summary>Writes the InternalsVisibleTo files that are needed and missing. Returns the paths written.</summary>
        public List<string> WriteFiles()
        {
            List<string> written = new();

            foreach (Assembly assembly in required)
            {
                if (!writableFolders.TryGetValue(assembly.GetName().Name, out string folder) || string.IsNullOrEmpty(folder))
                    continue;

                string path = Path.Combine(folder, IVT_FILE_NAME).Replace('\\', '/');

                try
                {
                    if (File.Exists(path) && File.ReadAllText(path) == IVT_FILE_CONTENT)
                        continue;

                    File.WriteAllText(path, IVT_FILE_CONTENT);
                    written.Add(path);
                    Debug.Log($"[FastIoC] Generated: {path}");
                }
                catch (Exception ex)
                {
                    Debug.LogWarning($"[FastIoC] Could not write {path}: {ex.Message}");
                }
            }

            return written;
        }
    }
}
#endif
