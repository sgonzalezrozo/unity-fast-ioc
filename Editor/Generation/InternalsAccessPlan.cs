#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.Compilation;
using Assembly = System.Reflection.Assembly;
using UnityEngine;

namespace FastIoC.Editor.Generation
{
    /// <summary>
    /// Decides which assemblies must expose their internals to Assembly-CSharp so the generated
    /// injectors can assign `internal` fields directly, and writes the InternalsVisibleTo files.
    ///
    /// Everything it writes stays in Assets/FastIoC/Generated: an assembly whose .asmdef lives under Assets/ gets
    /// <code>
    /// Generated/InternalsVisibleTo/&lt;Assembly&gt;/
    /// ├── &lt;Assembly&gt;.asmref                  compiles this folder into that assembly (by the .asmdef's GUID)
    /// └── FastIoC.InternalsVisibleTo.g.cs     [assembly: InternalsVisibleTo("Assembly-CSharp")]
    /// </code>
    /// so nothing is written next to the project's own .asmdef files. A folder whose assembly is gone is removed at the start of
    /// the next generation (Unity reports an Assembly Definition Reference to a missing assembly on every compile). Older versions wrote the .g.cs next to the
    /// .asmdef; an unchanged copy there is deleted. Assemblies in packages are never modified: they need
    /// [assembly: InternalsVisibleTo("Assembly-CSharp")] added by hand, otherwise their internal fields fall back to
    /// reflection (and generation logs which ones).
    /// </summary>
    internal sealed class InternalsAccessPlan
    {
        public const string IVT_FILE_NAME = "FastIoC.InternalsVisibleTo.g.cs";
        public const string IVT_FOLDER_NAME = "InternalsVisibleTo";

        private const string IVT_FILE_CONTENT =
            "// <auto-generated>\n" +
            "// Written by FastIoC code generation. Lets the generated injectors in Assembly-CSharp\n" +
            "// assign `internal` fields of this assembly directly, without reflection.\n" +
            "// </auto-generated>\n" +
            "[assembly: System.Runtime.CompilerServices.InternalsVisibleTo(\"Assembly-CSharp\")]\n";

        // Assembly name to the folder of its .asmdef under Assets/, and to the .asmdef's GUID.
        private readonly Dictionary<string, string> writableFolders = new();
        private readonly Dictionary<string, string> asmdefGuids = new();
        private readonly HashSet<string> playerAssemblyNames = new();
        private readonly HashSet<Assembly> required = new();

        public IReadOnlyCollection<string> PlayerAssemblyNames => playerAssemblyNames;

        public static InternalsAccessPlan Create()
        {
            CodeGenTypeUtility.ClearCache();
            InternalsAccessPlan plan = new();
            plan.playerAssemblyNames.Add(CodeGenTypeUtility.GENERATED_ASSEMBLY_NAME);

            try
            {
                foreach (UnityEditor.Compilation.Assembly compiledAssembly in CompilationPipeline.GetAssemblies(AssembliesType.PlayerWithoutTestAssemblies))
                {
                    plan.playerAssemblyNames.Add(compiledAssembly.name);

                    string asmdefPath = CompilationPipeline.GetAssemblyDefinitionFilePathFromAssemblyName(compiledAssembly.name);
                    if (string.IsNullOrEmpty(asmdefPath))
                        continue;

                    asmdefPath = asmdefPath.Replace('\\', '/');
                    if (!asmdefPath.StartsWith("Assets/", StringComparison.Ordinal))
                        continue;

                    plan.writableFolders[compiledAssembly.name] = Path.GetDirectoryName(asmdefPath)?.Replace('\\', '/');
                    plan.asmdefGuids[compiledAssembly.name] = AssetDatabase.AssetPathToGUID(asmdefPath);
                }
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[FastIoC] Could not read the compilation pipeline assemblies: {ex.Message}");
            }

            return plan;
        }

        /// <summary>True if Assembly-CSharp can (or will, after this generation) see the internals of <paramref name="assembly"/>.</summary>
        public bool Grants(Assembly assembly)
        {
            if (assembly == null)
                return false;

            return CodeGenTypeUtility.AlreadyGrantsInternals(assembly) || writableFolders.ContainsKey(assembly.GetName().Name);
        }

        /// <summary>Records that generated code uses internals of <paramref name="assembly"/>.</summary>
        public void Require(Assembly assembly)
        {
            // An assembly whose grant comes only from an old copy next to its .asmdef still gets the files in
            // Generated, so that copy can go.
            if (assembly != null && (!CodeGenTypeUtility.AlreadyGrantsInternals(assembly) || HasLegacyCopy(assembly)))
                required.Add(assembly);
        }

        private bool HasLegacyCopy(Assembly assembly)
        {
            if (!writableFolders.TryGetValue(assembly.GetName().Name, out string folder) || string.IsNullOrEmpty(folder))
                return false;

            string legacy = $"{folder}/{IVT_FILE_NAME}";
            try
            {
                return File.Exists(legacy) && File.ReadAllText(legacy) == IVT_FILE_CONTENT;
            }
            catch (IOException)
            {
                return false;
            }
        }

        /// <summary>Records the assemblies needed to name <paramref name="type"/>.</summary>
        public void RequireForType(Type type)
        {
            HashSet<Assembly> assemblies = new();
            CodeGenTypeUtility.CollectInternalAssemblies(type, assemblies);
            foreach (Assembly assembly in assemblies)
                Require(assembly);
        }

        /// <summary>The folder that holds one subfolder per assembly: Assets/FastIoC/Generated/InternalsVisibleTo.</summary>
        public static string RootFolder
            => $"{FastIoC.Core.FastIoCConstants.GENERATED_PATH}/{IVT_FOLDER_NAME}";

        /// <summary>
        /// Writes the InternalsVisibleTo files that are needed and missing, removes the folders of assemblies that no
        /// longer exist, and deletes the copies older versions wrote next to the .asmdef. Returns the paths written.
        /// </summary>
        public List<string> WriteFiles()
        {
            List<string> written = new();
            RemoveOrphanFolders();

            foreach (Assembly assembly in required)
            {
                string name = assembly.GetName().Name;
                if (!writableFolders.TryGetValue(name, out string asmdefFolder) || string.IsNullOrEmpty(asmdefFolder))
                    continue;
                if (!asmdefGuids.TryGetValue(name, out string guid) || string.IsNullOrEmpty(guid))
                    continue;

                string folder = $"{RootFolder}/{name}";
                WriteIfChanged($"{folder}/{name}.asmref", AsmrefContent(guid), written);
                WriteIfChanged($"{folder}/{IVT_FILE_NAME}", IVT_FILE_CONTENT, written);
                DeleteLegacyCopy(asmdefFolder);
            }

            return written;
        }

        /// <summary>An Assembly Definition Reference that compiles its folder into the assembly with this .asmdef GUID.</summary>
        internal static string AsmrefContent(string asmdefGuid)
            => "{\n    \"reference\": \"GUID:" + asmdefGuid + "\"\n}\n";

        private static void WriteIfChanged(string path, string content, List<string> written)
        {
            try
            {
                if (File.Exists(path) && File.ReadAllText(path) == content)
                    return;

                Directory.CreateDirectory(Path.GetDirectoryName(path) ?? RootFolder);
                File.WriteAllText(path, content);
                written.Add(path);
                Debug.Log($"[FastIoC] Generated: {path}");
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[FastIoC] Could not write {path}: {ex.Message}");
            }
        }

        /// <summary>
        /// Removes the folders whose .asmref points at an .asmdef that no longer exists: Unity reports such a reference
        /// on every compile. Runs at the start of every generation, even one that ends early with no installers.
        /// </summary>
        public static void RemoveOrphanFolders()
        {
            if (!Directory.Exists(RootFolder))
                return;

            foreach (string folder in Directory.GetDirectories(RootFolder))
            {
                string assetPath = folder.Replace('\\', '/');
                if (HasLiveTarget(assetPath))
                    continue;

                if (!AssetDatabase.DeleteAsset(assetPath) && Directory.Exists(assetPath))
                {
                    Directory.Delete(assetPath, true);
                    if (File.Exists(assetPath + ".meta"))
                        File.Delete(assetPath + ".meta");
                }
                Debug.Log($"[FastIoC] Removed {assetPath}: its assembly no longer exists.");
            }

            if (Directory.GetFileSystemEntries(RootFolder).Length == 0 && !AssetDatabase.DeleteAsset(RootFolder))
                Directory.Delete(RootFolder);
        }

        /// <summary>True when the folder's .asmref points at an .asmdef that still exists.</summary>
        private static bool HasLiveTarget(string folder)
        {
            foreach (string asmref in Directory.GetFiles(folder, "*.asmref"))
            {
                Match match = Regex.Match(File.ReadAllText(asmref), "GUID:([0-9a-fA-F]{32})");
                if (match.Success && !string.IsNullOrEmpty(AssetDatabase.GUIDToAssetPath(match.Groups[1].Value)))
                    return true;
            }

            return false;
        }

        /// <summary>Before 0.11.2 the file was written next to the .asmdef. An unchanged copy there is deleted.</summary>
        private static void DeleteLegacyCopy(string asmdefFolder)
        {
            string legacy = $"{asmdefFolder}/{IVT_FILE_NAME}";
            try
            {
                if (!File.Exists(legacy) || File.ReadAllText(legacy) != IVT_FILE_CONTENT)
                    return;

                if (!AssetDatabase.DeleteAsset(legacy))
                {
                    File.Delete(legacy);
                    if (File.Exists(legacy + ".meta"))
                        File.Delete(legacy + ".meta");
                }
                Debug.Log($"[FastIoC] Moved {legacy} into {RootFolder}.");
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[FastIoC] Could not delete {legacy}: {ex.Message}");
            }
        }
    }
}
#endif
